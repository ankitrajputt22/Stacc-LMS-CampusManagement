#!/usr/bin/env python3
"""Writes docs/authorization-matrix.md: every API route with the role and permission rule on it, read from the
controllers' @*Mapping and @PreAuthorize annotations (constants resolved). Routes without @PreAuthorize are listed as
"signed in" unless SecurityConfig makes them public. Run from the repository root: python3 scripts/authorization-matrix.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "backend/src/main/java"
PUBLIC = {
    ("POST", "/api/v1/auth/login"),
    ("GET", "/api/v1/calendar/feeds/{token}.ics"),
    ("GET", "/api/v1/public/documents/verify/{code}"),
}

def constants(text, shared):
    found = dict(shared)
    for name, value in re.findall(r'static final String (\w+)\s*=\s*(.+?);', text, re.S):
        found[name] = value
    def resolve(expr, depth=0):
        if depth > 6:
            return expr
        parts = re.split(r'\s*\+\s*', expr.strip())
        out = []
        for part in parts:
            part = part.strip()
            if part.startswith('"'):
                out.append(part.strip('"'))
            else:
                key = part.split('.')[-1]
                out.append(resolve(found[key], depth + 1) if key in found else part)
        return "".join(out)
    return {k: resolve(v) for k, v in found.items()}, resolve

shared_text = "".join(p.read_text() for p in SRC.rglob("*Access.java"))
shared, _ = constants(shared_text, {})
rows = []
for path in sorted(SRC.rglob("*Controller.java")):
    text = path.read_text()
    consts, resolve = constants(text, shared)
    head = text[:text.find("public class")]
    base = re.search(r'@RequestMapping\("([^"]*)"\)', head)
    prefix = base.group(1) if base else ""
    for match in re.finditer(r'@(Get|Post|Put|Delete|Patch)Mapping\(([^)]*)\)(.*?)public ', text, re.S):
        verb, args, rest = match.group(1).upper(), match.group(2), match.group(3)
        literal = re.search(r'"([^"]*)"', args)
        route = literal.group(1) if literal else ""
        for name, value in consts.items():
            if re.search(r'\b' + name + r'\b', args) and not literal:
                route = value
        if not literal:
            ref = re.search(r'(?:value\s*=\s*)?([A-Z_]+)(?:\s*\+\s*"([^"]*)")?', args)
            if ref and ref.group(1) in consts:
                route = consts[ref.group(1)] + (ref.group(2) or "")
        full = (prefix + route) if not route.startswith("/api") else route
        rule = re.search(r'@PreAuthorize\((.*)\)\s*$', rest, re.M)
        if rule:
            expr = rule.group(1).strip()
            text_rule = expr.strip('"') if expr.startswith('"') and expr.endswith('"') and '" +' not in expr else resolve(expr)
        else:
            text_rule = "public" if (verb, full) in PUBLIC else "signed in"
        rows.append((full, verb, text_rule, path.stem))

lines = ["# Authorization matrix", "",
         "Generated by `scripts/authorization-matrix.py` from the controllers. Every rule here only lets a caller ask; the",
         "services still check each record (owner, teacher, officer, warden, team) and answer 404 for anything else.", "",
         "| Route | Method | Rule | Controller |", "| --- | --- | --- | --- |"]
for full, verb, rule, controller in sorted(rows):
    lines.append(f"| `{full}` | {verb} | `{rule}` | {controller} |")
(ROOT / "docs/authorization-matrix.md").write_text("\n".join(lines) + "\n")
print(f"{len(rows)} routes written to docs/authorization-matrix.md")
